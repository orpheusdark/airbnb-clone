const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..', 'views');
const files = [];
function walk(folder) {
  for (const entry of fs.readdirSync(folder, { withFileTypes: true })) {
    const file = path.join(folder, entry.name);
    if (entry.isDirectory()) walk(file);
    else if (entry.name.endsWith('.ejs')) files.push(path.relative(root, file).replaceAll(path.sep, '/'));
  }
}
walk(root);
const source = '// Generated by scripts/build-views.js. Explicit references preserve EJS assets during serverless tracing.\nmodule.exports = [\n' + files.sort().map((name) => `  require.resolve(${JSON.stringify('../views/' + name)}),`).join('\n') + '\n];\n';
fs.writeFileSync(path.join(__dirname, '..', 'lib', 'view-assets.js'), source);
console.log(`Registered ${files.length} EJS templates for deployment.`);
